"""
Справочные данные по видам сорняков: тип, общие рекомендации по гербицидам
и заметки о влиянии фазы вегетации на эффективность обработки.

Это общая агрономическая справка для демо-MVP, а НЕ инструкция по
применению конкретного препарата — перед реальной обработкой всегда
нужно свериться с этикеткой препарата и региональными регламентами.
"""

# Классы детектора формируются как "<вид сорняка> / <фаза роста>"
# (см. src/prepare_dataset.py::CLASS_SEP).
CLASS_SEP = " / "

SPECIES_INFO = {
    "Бодяк полевой": {
        "type": "многолетний, двудольный (корнеотпрысковый)",
        "herbicides": ["2,4-Д", "дикамба", "клопиралид", "глифосат (на парах/до посева)"],
        "note": "Системные гербициды эффективнее всего в фазе розетки — активный "
                "отток к корневой системе. На стадии стеблевания/бутонизации "
                "эффективность обработки заметно падает.",
    },
    "Вьюнок полевой": {
        "type": "многолетний, двудольный (вьющийся, корнеотпрысковый)",
        "herbicides": ["2,4-Д", "дикамба", "сульфонилмочевины (напр. метсульфурон-метил)",
                        "глифосат (на парах/стерне)"],
        "note": "Как и у бодяка, ранняя фаза (розетка/начало вегетации) даёт лучшее "
                "системное действие. Плотная корневая система требует, как правило, "
                "повторной обработки.",
    },
    "Пырей ползучий": {
        "type": "многолетний, злаковый (корневищный)",
        "herbicides": ["глифосат сплошного действия", "граминициды (клетодим, флуазифоп — "
                        "в посевах широколистных культур)"],
        "note": "Злаковый сорняк — большинство противодвудольных гербицидов (2,4-Д, "
                "дикамба) на него не действуют, нужен граминицид или глифосат "
                "сплошного действия по стерне/парам.",
    },
}

STAGE_TIMING_NOTE = {
    "Розетка": "Ранняя фаза — оптимальное окно для системной химической обработки.",
    "Стеблевание": "Более поздняя фаза — обработка ещё возможна, но эффективность ниже, "
                   "предпочтительны более высокие нормы или механическое удаление.",
}


def split_class_name(class_name):
    """'Бодяк полевой / Розетка' -> ('Бодяк полевой', 'Розетка')."""
    if CLASS_SEP in class_name:
        species, stage = class_name.split(CLASS_SEP, 1)
        return species.strip(), stage.strip()
    return class_name.strip(), None


def get_recommendation(class_name):
    """Возвращает dict с рекомендацией для конкретного класса детектора."""
    species, stage = split_class_name(class_name)
    info = SPECIES_INFO.get(species)
    if info is None:
        return {
            "species": species,
            "stage": stage,
            "type": "нет данных",
            "herbicides": [],
            "note": "Справочные данные для этого вида отсутствуют.",
        }

    stage_note = STAGE_TIMING_NOTE.get(stage, "")
    return {
        "species": species,
        "stage": stage,
        "type": info["type"],
        "herbicides": info["herbicides"],
        "note": (info["note"] + (" " + stage_note if stage_note else "")).strip(),
    }
